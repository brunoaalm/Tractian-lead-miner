def _buscar_cnaes_secundarios(cnpj_basico: str) -> list:
    """Busca CNAEs secundários da tabela cnae_secundario."""
    try:
        conn = get_connection()
        cur = conn.cursor(cursor_factory=RealDictCursor)
        cur.execute(
            "SELECT cnae_secundario FROM cnae_secundario WHERE cnpj_basico = %s",
            (cnpj_basico.zfill(8),)
        )
        rows = cur.fetchall()
        conn.close()
        return [r["cnae_secundario"] for r in rows if r["cnae_secundario"]]
    except Exception:
        return []


@exportar_bp.route("/exportar", methods=["POST"])
def exportar():
    dados = request.get_json(silent=True) or []
    if not dados:
        return jsonify({"error": "Nenhum dado para exportar."}), 400

    # Enriquece cada linha com sócios e CNAEs secundários
    linhas_enriquecidas = []
    for row in dados:
        cnpj_basico = str(row.get("cnpj_basico", "") or "").strip()

        # Sócios: "NOME (Cargo) | NOME2 (Cargo2)"
        socios_raw = buscar_socios(cnpj_basico) if cnpj_basico else []
        socios_str = " | ".join(
            f"{s.get('nome_socio', '').strip()} ({s.get('cargo', '') or s.get('qualificacao_socio', '')})"
            for s in socios_raw
        ) if socios_raw else ""

        # CNAEs secundários: "1234500 | 9876500"
        cnaes_sec = _buscar_cnaes_secundarios(cnpj_basico) if cnpj_basico else []
        cnaes_sec_str = " | ".join(cnaes_sec)

        # Descrição do CNAE principal
        cnae_principal = str(row.get("cnae_principal", "") or "").strip()
        cnae_desc = CNAE_DESC.get(cnae_principal, "")

        linha = dict(row)
        linha["socios"]             = socios_str
        linha["cnaes_secundarios"]  = cnaes_sec_str
        linha["cnae_desc"]          = cnae_desc
        linhas_enriquecidas.append(linha)

    output = io.StringIO()
    writer = csv.writer(output, delimiter=";")

    writer.writerow([label for _, label in COLUNAS])

    for row in linhas_enriquecidas:
        writer.writerow([row.get(key, "") for key, _ in COLUNAS])

    output.seek(0)
    bytes_output = io.BytesIO(("﻿" + output.getvalue()).encode("utf-8"))

    return send_file(
        bytes_output,
        mimetype="text/csv",
        as_attachment=True,
        download_name="leads_tractian.csv",
    )
